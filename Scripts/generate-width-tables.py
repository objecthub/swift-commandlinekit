#!/usr/bin/env python3
#
# generate-width-tables.py
# CommandLineKit
#
# Generates `Sources/CommandLineKit/TerminalWidthTables.swift`, the tables used by
# `Unicode.Scalar.terminalDisplayWidth` to determine how many columns a Unicode scalar
# occupies on a monospaced terminal. The data is derived from the Unicode Character
# Database as shipped with Python's `unicodedata` module (general categories and the
# East Asian Width property). Since Unicode 9, all characters with the property
# Emoji_Presentation=Yes have East Asian Width W, i.e. the emoji data is covered by
# the East Asian Width property. The only exception are the regional indicators
# U+1F1E6-U+1F1FF (East Asian Width N) which are narrow individually; a pair of
# regional indicators (a flag) has width 2.
#
# Usage (run from the root of the repository with the newest Python available, since
# the Unicode version is determined by the Python version):
#
#   python3 Scripts/generate-width-tables.py > Sources/CommandLineKit/TerminalWidthTables.swift
#
# Rules:
#   - Width 0: general categories Cc, Mn, Me, Cf, Zl, Zp (except U+00AD SOFT HYPHEN
#     and the prepended concatenation marks, which are visible), Hangul Jungseong and
#     Jongseong (U+1160-U+11FF, U+D7B0-U+D7FF) which combine with a preceding Choseong,
#     and unassigned default ignorable code points.
#   - Width 2: East Asian Width W (wide) or F (fullwidth), and unassigned code points in
#     ranges which are reserved for wide characters (the default W ranges of
#     EastAsianWidth.txt, i.e. CJK blocks and planes 2 and 3, as well as blocks reserved
#     for future emoji and ideographic scripts).
#   - Width 1: everything else, including East Asian Width A (ambiguous).

import sys
import unicodedata

PREPENDED_CONCATENATION_MARKS = set(
  list(range(0x0600, 0x0606)) + [0x06DD, 0x070F, 0x0890, 0x0891, 0x08E2, 0x110BD, 0x110CD])

VISIBLE_FORMAT_CHARACTERS = {0x00AD} | PREPENDED_CONCATENATION_MARKS

ZERO_WIDTH_CATEGORIES = {'Cc', 'Mn', 'Me', 'Cf', 'Zl', 'Zp'}

# Hangul Jungseong and Jongseong (medial vowels and final consonants)
CONJOINING_JAMO = [(0x1160, 0x11FF), (0xD7B0, 0xD7FF)]

# Unassigned default ignorable code points
UNASSIGNED_ZERO_WIDTH = [(0x2060, 0x206F), (0xFFF0, 0xFFF8), (0xE0000, 0xE0FFF)]

# Unassigned code points which are reserved for wide characters
UNASSIGNED_WIDE = [
  (0x3400, 0x4DBF),    # CJK Unified Ideographs Extension A
  (0x4E00, 0x9FFF),    # CJK Unified Ideographs
  (0xF900, 0xFAFF),    # CJK Compatibility Ideographs
  (0x16FE0, 0x16FFF),  # Ideographic Symbols and Punctuation
  (0x17000, 0x18DFF),  # Tangut, Tangut Components, Khitan Small Script, Tangut Supplement
  (0x1AFF0, 0x1B2FF),  # Kana Extended-B, Kana Supplement, Kana Extended-A, Small Kana, Nushu
  (0x1F300, 0x1F64F),  # Miscellaneous Symbols and Pictographs, Emoticons
  (0x1F680, 0x1F6FF),  # Transport and Map Symbols
  (0x1F900, 0x1F9FF),  # Supplemental Symbols and Pictographs
  (0x1FA70, 0x1FAFF),  # Symbols and Pictographs Extended-A
  (0x20000, 0x2FFFD),  # Plane 2
  (0x30000, 0x3FFFD),  # Plane 3
]

def in_ranges(cp, ranges):
  return any(lo <= cp <= hi for (lo, hi) in ranges)

def width(cp):
  if 0xD800 <= cp <= 0xDFFF:  # Surrogates are not Unicode scalars
    return 1
  c = chr(cp)
  category = unicodedata.category(c)
  if cp in VISIBLE_FORMAT_CHARACTERS:
    return 1
  if category in ZERO_WIDTH_CATEGORIES or in_ranges(cp, CONJOINING_JAMO):
    return 0
  if category == 'Cn' and in_ranges(cp, UNASSIGNED_ZERO_WIDTH):
    return 0
  if unicodedata.east_asian_width(c) in ('W', 'F'):
    return 2
  if category == 'Cn' and in_ranges(cp, UNASSIGNED_WIDE):
    return 2
  return 1

def ranges_with_width(w):
  result = []
  start = None
  for cp in range(0, 0x110000):
    if width(cp) == w:
      if start is None:
        start = cp
    elif start is not None:
      result.append((start, cp - 1))
      start = None
  if start is not None:
    result.append((start, 0x10FFFF))
  return result

def emit_table(name, comment, ranges):
  lines = [f'  /// {comment}',
           f'  /// ({len(ranges)} ranges, each represented by its first and last code point)',
           f'  static let {name}: [UInt32] = [']
  entries = [f'0x{lo:05X}, 0x{hi:05X}' for (lo, hi) in ranges]
  for i in range(0, len(entries), 4):
    lines.append('    ' + ', '.join(entries[i:i + 4]) + ',')
  lines.append('  ]')
  return '\n'.join(lines)

